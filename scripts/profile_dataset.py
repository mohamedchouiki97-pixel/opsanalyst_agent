"""Profile any Postgres schema and write a DRAFT data dictionary for a human to edit.

Works on any database (not just TPC-H). It reads Postgres's own catalog:
tables/views, columns, types, primary/foreign keys, row estimates, and the most
common values of low-cardinality columns (from planner statistics, so no table scans).

It writes <dataset>/dictionary.draft.yaml and never touches dictionary.yaml, so
hand-written descriptions are never overwritten.

Usage:
    uv run python scripts/profile_dataset.py --schema tpch --out datasets/tpch/dictionary.draft.yaml
"""

import argparse
from contextlib import closing
from pathlib import Path

import yaml

from agent.db import connect

MAX_SAMPLE_VALUES = 25  # columns with more distinct values than this get no samples

TABLES_SQL = """
SELECT c.relname,
       CASE c.relkind WHEN 'v' THEN 'view' ELSE 'table' END,
       GREATEST(c.reltuples, 0)::bigint
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = :schema AND c.relkind IN ('r', 'v')
ORDER BY c.relkind, c.relname
"""

COLUMNS_SQL = """
SELECT table_name, column_name, data_type, is_nullable = 'YES'
FROM information_schema.columns
WHERE table_schema = :schema
ORDER BY table_name, ordinal_position
"""

PRIMARY_KEYS_SQL = """
SELECT t.relname, a.attname
FROM pg_constraint c
JOIN pg_class t ON t.oid = c.conrelid
JOIN pg_namespace n ON n.oid = t.relnamespace
CROSS JOIN LATERAL unnest(c.conkey) AS k(attnum)
JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum
WHERE c.contype = 'p' AND n.nspname = :schema
"""

FOREIGN_KEYS_SQL = """
SELECT t.relname, a.attname, ft.relname, fa.attname
FROM pg_constraint c
JOIN pg_class t  ON t.oid = c.conrelid
JOIN pg_class ft ON ft.oid = c.confrelid
JOIN pg_namespace n ON n.oid = t.relnamespace
CROSS JOIN LATERAL unnest(c.conkey, c.confkey) AS k(attnum, fattnum)
JOIN pg_attribute a  ON a.attrelid = c.conrelid   AND a.attnum = k.attnum
JOIN pg_attribute fa ON fa.attrelid = c.confrelid AND fa.attnum = k.fattnum
WHERE c.contype = 'f' AND n.nspname = :schema
"""

# n_distinct > 0 is an absolute count; negative values mean "a fraction of rows" (= many).
COMMON_VALUES_SQL = """
SELECT tablename, attname, most_common_vals::text::text[]
FROM pg_stats
WHERE schemaname = :schema
  AND n_distinct BETWEEN 1 AND :max_values
  AND most_common_vals IS NOT NULL
"""


def profile(schema: str) -> dict:
    with closing(connect()) as conn:
        tables = conn.run(TABLES_SQL, schema=schema)
        columns = conn.run(COLUMNS_SQL, schema=schema)
        primary_keys = conn.run(PRIMARY_KEYS_SQL, schema=schema)
        foreign_keys = conn.run(FOREIGN_KEYS_SQL, schema=schema)
        common_values = conn.run(COMMON_VALUES_SQL, schema=schema, max_values=MAX_SAMPLE_VALUES)

    pk_columns = {(table, column) for table, column in primary_keys}
    references = {(t, c): f"{ft}.{fc}" for t, c, ft, fc in foreign_keys}
    samples = {(t, c): sorted(values) for t, c, values in common_values}

    result = {}
    for table, kind, row_estimate in tables:
        result[table] = {
            "kind": kind,
            "row_estimate": row_estimate,
            "description": "TODO",
            "columns": {},
        }

    for table, column, data_type, nullable in columns:
        if table not in result:
            continue
        info = {"type": data_type, "description": "TODO"}
        if (table, column) in pk_columns:
            info["primary_key"] = True
        if not nullable:
            info["not_null"] = True
        if (table, column) in references:
            info["references"] = references[(table, column)]
        is_key = (table, column) in pk_columns or (table, column) in references
        if (table, column) in samples and not is_key:  # key values are IDs, not categories
            info["sample_values"] = samples[(table, column)]
        result[table]["columns"][column] = info

    return {"schema": schema, "tables": result}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", required=True, help="Postgres schema to profile")
    parser.add_argument("--out", required=True, type=Path, help="output .draft.yaml path")
    args = parser.parse_args()

    if args.out.name == "dictionary.yaml":
        raise SystemExit("Refusing to overwrite dictionary.yaml. Write a .draft.yaml instead.")

    draft = profile(args.schema)
    args.out.write_text(
        "# DRAFT generated by scripts/profile_dataset.py. Copy what you need into\n"
        "# dictionary.yaml and replace every TODO with a real description.\n"
        + yaml.safe_dump(draft, sort_keys=False, allow_unicode=True, width=100),
        encoding="utf-8",
    )
    print(f"Profiled {len(draft['tables'])} tables/views -> {args.out}")


if __name__ == "__main__":
    main()
